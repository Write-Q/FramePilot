const {test} = require('node:test');
const assert = require('node:assert/strict');
const {chromium} = require('playwright');
const fs = require('node:fs');
const base = process.env.FRAMEPILOT_UI_URL;

test('分镜生成、编辑、排序、版本、确认与移动端', async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.FRAMEPILOT_CHROME ? {executablePath:process.env.FRAMEPILOT_CHROME} : {})});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const json = async (url, body) => {
    const r = await page.request.post(base+url, {data:body});
    assert.ok(r.ok(), await r.text()); return r.json();
  };
  try {
    const project = await json('/api/projects', {story:'小禾把唯一的钥匙交给阿林。小禾随后用这把钥匙打开门。'});
    await json(`/api/projects/${project.id}/resume`, {action:'confirm',version:1,interrupt_id:project.interrupt.id});
    await page.goto(base+'/storyboard?project='+project.id);
    await page.waitForLoadState('networkidle');
    await page.locator('#source-state').filter({hasText:'已确认'}).waitFor();
    await page.locator('#config-details').evaluate(el=>el.open=true);
    await page.locator('#config-name').fill('测试分镜模型');
    await page.locator('#config-url').fill('https://example.test/v1');
    await page.locator('#config-model').fill('test-planner');
    await page.locator('#config-save').click();
    await page.locator('#profile option').filter({hasText:'测试分镜模型'}).waitFor({state:'attached'});
    await page.locator('#target-shots').fill('1');
    await page.locator('#generate').click();
    await page.locator('.shot-card').waitFor();
    assert.equal(await page.locator('.shot-card').count(),1);
    const dialogue=page.locator('#edit-dialogue_lines');
    await dialogue.evaluate(el=>{const group=el.closest('details');if(group)group.open=true;});
    await dialogue.fill('没有分隔符的台词');
    await page.locator('#save-board').click();
    assert.match(await page.locator('#board-version').textContent(),/V1/);
    assert.equal(await dialogue.inputValue(),'没有分隔符的台词');
    await page.locator('.shot-card').first().click();
    assert.equal(await dialogue.inputValue(),'没有分隔符的台词');
    await dialogue.fill('小禾｜拿好。');
    await page.locator('#edit-action').fill('小禾伸手递出钥匙，阿林接住。');
    assert.equal(await page.locator('#confirm-board').isDisabled(),true);
    await page.locator('#save-board').click();
    await page.locator('#board-version').filter({hasText:'V2'}).waitFor();
    await page.locator('#review-read').check();
    await page.locator('#confirm-board').click();
    await page.locator('#board-state').filter({hasText:'已确认'}).waitFor();
    await page.reload();
    await page.locator('#board-state').filter({hasText:'已确认'}).waitFor();
    assert.equal(await page.locator('#edit-action').inputValue(),'小禾伸手递出钥匙，阿林接住。');
    await page.locator('#history-version').selectOption('1');
    await page.locator('#edit-action:disabled').waitFor();
    assert.equal(await page.locator('#confirm-board').isDisabled(),true);
    await page.locator('#history-version').selectOption('2');
    await page.locator('#add-shot').click();
    assert.equal(await page.locator('.shot-card').count(),2);
    await page.locator('#move-up').click();
    await page.locator('#delete-shot').click();
    assert.equal(await page.locator('.shot-card').count(),1);
    await page.locator('#save-board').click();
    await page.locator('#board-version').filter({hasText:'V3'}).waitFor();
    assert.match(await page.locator('#board-state').textContent(),/待确认/);
    await page.locator('#add-shot').click();
    await dialogue.evaluate(el=>el.closest('details').open=true);
    await dialogue.fill('第二镜无效且尚未解析的台词');
    page.once('dialog',dialog=>dialog.accept());
    await page.reload();
    await page.locator('#dirty-state').filter({hasText:'有未保存修改'}).waitFor();
    await page.locator('#save-board').click();
    assert.match(await page.locator('#editor-heading').textContent(),/02/);
    assert.equal(await dialogue.inputValue(),'第二镜无效且尚未解析的台词');
    assert.match(await page.locator('#board-version').textContent(),/V3/);
    await dialogue.fill('');
    await page.locator('#delete-shot').click();
    await page.locator('#save-board').click();
    await page.locator('#board-version').filter({hasText:'V4'}).waitFor();
    const original=await page.request.get(base+`/api/production/projects/${project.id}/storyboard-runs`);
    const runs=await original.json();
    await page.evaluate(({projectId,payload})=>sessionStorage.setItem('framepilot:board-pending:'+projectId,JSON.stringify(payload)),{projectId:project.id,payload:runs[0].manifest.request});
    await page.locator('#refresh-runs').click();
    await page.waitForFunction(id=>sessionStorage.getItem('framepilot:board-pending:'+id)===null,project.id);
    const countBefore=runs.length;
    await page.locator('#target-shots').fill('0');
    // A server-side precondition rejection must not leave a phantom pending request.
    await page.locator('#target-shots').fill('1');
    await page.route('**/storyboard-runs',async route=>{
      if(route.request().method()==='POST')await route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({detail:'测试中的来源冲突'})});
      else await route.continue();
    });
    await page.locator('#generate').click();
    await page.locator('#error').filter({hasText:'来源冲突'}).waitFor();
    assert.equal(await page.evaluate(id=>sessionStorage.getItem('framepilot:board-pending:'+id),project.id),null);
    await page.unroute('**/storyboard-runs');
    assert.equal((await (await page.request.get(base+`/api/production/projects/${project.id}/storyboard-runs`)).json()).length,countBefore);
    await page.locator('#refresh-runs').click();
    fs.mkdirSync('.runtime/storyboard-qa',{recursive:true});
    await page.screenshot({path:'.runtime/storyboard-qa/desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:'.runtime/storyboard-qa/mobile.png',fullPage:true});
    assert.deepEqual(errors,[]);
  } finally { await browser.close(); }
});
