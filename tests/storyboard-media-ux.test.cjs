const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require('playwright');

test('图片制作：确认门禁、候选选用、未知状态与幂等恢复',async()=>{
  assert.ok(fs.existsSync('app/static/storyboard-media.js'),'media module exists');
  const browser=await chromium.launch({headless:true,...(process.env.FRAMEPILOT_CHROME?{executablePath:process.env.FRAMEPILOT_CHROME}:{})});
  const page=await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  try {
    await page.route('**/*',route=>route.fulfill({contentType:'text/html',body:fs.readFileSync('app/static/storyboard.html','utf8').replace(/<script[\s\S]*?<\/script>/g,'')}));
    await page.goto('http://localhost/storyboard');
    await page.addStyleTag({content:fs.readFileSync('app/static/storyboard.css','utf8')});
    await page.evaluate(()=>{
      window.$=id=>document.getElementById(id);window.project={id:'p'};
      window.current={id:'b',version:1,current_version:1,confirmed:false,source_current:true,source_confirmed:true};
      window.draft={aspect_ratio:'16:9',shots:[{key:'shot-1'},{key:'shot-2'}]};window.selected=0;window.dirty=false;window.working=false;
      window.readonly=()=>current.version!==current.current_version||!current.source_current;
      window.node=(tag,text,cls)=>{const el=document.createElement(tag);if(text!==undefined)el.textContent=text;if(cls)el.className=cls;return el;};
      window.readMemory=k=>JSON.parse(sessionStorage.getItem(k)||'null');window.memory=(k,v)=>v===null?sessionStorage.removeItem(k):sessionStorage.setItem(k,JSON.stringify(v));
      window.boardUrl=()=>'/boards/b';window.prefix='/api/production';window.notice=()=>{};window.renderShots=()=>{};window.profiles=async()=>{};
      window.testRuns=[];window.requests=[];window.failNext=false;
      window.api=async(url,body)=>{if(body){requests.push({url,body});if(failNext){failNext=false;throw Error('响应丢失');}if(url.endsWith('/select'))return {};return {id:'run-1',status:'queued'};}if(url.includes('frame-prompt'))return {prompt:'静态画面草稿',manifest:{}};return {runs:testRuns,selections:[]};};
      window.busy=async fn=>{working=true;StoryboardMedia.availability();try{await fn();}catch(e){$('error').textContent=e.message;$('error').hidden=false;}finally{working=false;StoryboardMedia.availability();}};
      $('board').hidden=false;
    });
    await page.addScriptTag({content:fs.readFileSync('app/static/storyboard-media.js','utf8')});
    await page.evaluate(async()=>{StoryboardMedia.setProfiles([{id:'im',version:1,config:{name:'图像测试',model:'image',purpose:'image',adapter:'openai_images'}}]);await StoryboardMedia.refresh();});
    assert.equal(await page.locator('#generate-image').isDisabled(),true);
    await page.evaluate(()=>{current.confirmed=true;StoryboardMedia.availability();});
    await page.locator('#image-profile').selectOption('im:1');
    await page.locator('#preview-frame-prompt').click();
    assert.equal(await page.locator('#frame-prompt').inputValue(),'静态画面草稿');
    await page.locator('#frame-prompt').fill('我的静态帧草稿');
    await page.evaluate(()=>{dirty=true;StoryboardMedia.availability();});
    assert.equal(await page.locator('#generate-image').isDisabled(),true);
    await page.evaluate(()=>{dirty=false;failNext=true;StoryboardMedia.availability();});
    await page.locator('#generate-image').click();
    await page.locator('#error').filter({hasText:'响应丢失'}).waitFor();
    await page.evaluate(()=>{selected=1;StoryboardMedia.render();});
    assert.match(await page.locator('#media-shot').textContent(),/shot-1.*待恢复/);
    assert.equal(await page.locator('#frame-prompt').isDisabled(),true);
    assert.equal(await page.locator('#frame-prompt').inputValue(),'我的静态帧草稿');
    await page.locator('#generate-image').click();
    await page.waitForFunction(()=>requests.length===2);
    await page.waitForFunction(()=>!working);
    assert.equal(await page.locator('#frame-prompt').inputValue(),'','恢复后回到当前镜头自己的草稿');
    const requests=await page.evaluate(()=>window.requests);assert.deepEqual(requests[0].body,requests[1].body);
    assert.equal(requests[0].body.prompt,'我的静态帧草稿');assert.equal(requests[0].body.size,'1536x864');
    await page.evaluate(async()=>{selected=0;testRuns=[{id:'r',status:'succeeded',version:1,shot_key:'shot-1',frame_role:'first',applicable:true,selected:false,media_url:'/media/test.png'},{id:'u',status:'unknown',version:1,shot_key:'shot-1',frame_role:'first',error:'响应未知'},{id:'q',status:'queued',version:1,shot_key:'shot-1',frame_role:'first'},{id:'active',status:'running',version:1,shot_key:'shot-1',frame_role:'first'}];await StoryboardMedia.refresh();});
    assert.equal(await page.locator('#media-candidates img').count(),1);
    assert.match(await page.locator('#media-candidates').textContent(),/不会自动重试/);
    assert.match(await page.locator('#media-candidates').textContent(),/等待生成服务处理/);
    assert.match(await page.locator('#media-candidates').textContent(),/不会取消外部生成请求/);
    await page.getByRole('button',{name:'选用此图',exact:true}).click();
    assert.equal((await page.evaluate(()=>requests.at(-1))).url,'/boards/b/media-runs/r/select');
    await page.evaluate(()=>{dirty=true;StoryboardMedia.availability();});
    assert.equal(await page.getByRole('button',{name:'选用此图',exact:true}).isDisabled(),true);
    await page.evaluate(()=>{dirty=false;current.current_version=2;StoryboardMedia.availability();});
    assert.equal(await page.locator('#generate-image').isDisabled(),true);
    await page.evaluate(()=>{current.current_version=1;selected=1;StoryboardMedia.render();});
    assert.equal(await page.locator('#media-candidates img').count(),0);
    await page.evaluate(()=>{selected=0;project.id='another-project';StoryboardMedia.render();});
    assert.equal(await page.locator('#media-candidates img').count(),0);
    assert.equal(await page.locator('#generate-image').isDisabled(),true);
    assert.equal(await page.evaluate(()=>requests.length),3,'刷新与切换不自动提交未知请求');
    await page.evaluate(async()=>{
      project.id='p';selected=0;current.version=2;current.current_version=2;current.confirmed=false;dirty=true;
      memory('framepilot:media-pending:p:b',{expected_version:1,shot_key:'shot-1',frame_role:'first',profile:{profile_id:'im',version:1},prompt:'旧请求',size:'1536x864',idempotency_key:'old-fixed-key'});
      const original=api;window.api=async(url,body)=>{if(body&&url.endsWith('/media-runs')){requests.push({url,body});const error=Error('版本已过期');error.status=409;throw error;}return original(url,body);};
      await StoryboardMedia.refresh();
    });
    assert.equal(await page.locator('#generate-image').isDisabled(),false,'脏稿新版本仍能核对旧请求');
    await page.getByRole('button',{name:'核对上次图片请求',exact:true}).click();
    await page.waitForFunction(()=>!working);
    assert.equal(await page.evaluate(()=>requests.at(-1).body.expected_version),1);
    assert.equal(await page.evaluate(()=>requests.at(-1).body.idempotency_key),'old-fixed-key');
    assert.equal(await page.evaluate(()=>readMemory('framepilot:media-pending:p:b')),null);
    assert.equal(await page.locator('#frame-prompt').inputValue(),'','旧版本核对结束不遗留旧提示词');
    assert.equal(await page.locator('#generate-image').isDisabled(),true,'核对结束后仍禁止脏稿生成新请求');
    await page.evaluate(async()=>{dirty=false;current.confirmed=true;await StoryboardMedia.refresh();});
    assert.equal(await page.locator('#generate-image').isDisabled(),false,'确认新版本后可继续制作');
    assert.equal(await page.locator('#frame-prompt').isDisabled(),false);
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    assert.deepEqual(errors,[]);
  }finally{await browser.close();}
});
